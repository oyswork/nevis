"""Generate src/nevis/db_models.py from schema/schema.sql with omymodels.

Run after every schema change: ``uv run python scripts/generate_models.py``.
tests/test_db_models.py fails if the checked-in file is stale.
"""

import io
from contextlib import redirect_stdout
from pathlib import Path

from omymodels import BaseGenerator, create_models, register_generator
from omymodels.models.pydantic_v2 import templates as pydantic_v2_templates
from omymodels.models.pydantic_v2.core import ModelGenerator as PydanticV2Generator
from table_meta.model import Column

ROOT = Path(__file__).resolve().parent.parent
SCHEMA_PATH = ROOT / "schema" / "schema.sql"
MODELS_PATH = ROOT / "src" / "nevis" / "db_models.py"

MODELS_TYPE = "pydantic_v2_aware"
# What the built-in generator emits for timestamptz columns (it has no mapping, so it passes
# the SQL type through) -> the type we want instead. The DDL parser reduces
# "timestamp with time zone" to plain "timestamp", so only the timestamptz spelling gets here.
AWARE_DATETIME_TYPES = {
    "timestamptz": "AwareDatetime",
    "list[timestamptz]": "list[AwareDatetime]",
}

HEADER = """\
# Generated by scripts/generate_models.py from schema/schema.sql. Do not edit by hand.
# One row model per table, as asyncpg returns it.
"""


# Extends the built-in generator as in omymodels' "Extending Built-in Generators" docs
# (example/extend_builtin_generator.py), with two deviations:
# - BaseGenerator is mixed in because register_generator rejects anything that doesn't inherit
#   it, and the built-in pydantic_v2 ModelGenerator doesn't (as of omymodels 1.0.0).
# - create_header adds the name to the generator's pydantic imports instead of prepending an
#   import line, so it lands in the existing `from pydantic import ...` line.
# create_header also drops `from __future__ import annotations`: redundant on Python 3.14, which
# evaluates annotations lazily (PEP 649).
# omymodels ships no type information, so both bases are Any to mypy.
class AwareDatetimeGenerator(PydanticV2Generator, BaseGenerator):  # type: ignore[misc]
    """The pydantic_v2 generator, but timestamptz columns become ``pydantic.AwareDatetime``."""

    def __init__(self) -> None:
        super().__init__()
        self.aware_datetime_import = False

    def get_not_custom_type(self, column: Column) -> str:
        _type = str(super().get_not_custom_type(column))
        if _type in AWARE_DATETIME_TYPES:
            self.aware_datetime_import = True
            return AWARE_DATETIME_TYPES[_type]
        return _type

    def create_header(self, *args: object, **kwargs: object) -> str:
        if self.aware_datetime_import:
            self.imports.add("AwareDatetime")
        header = str(super().create_header(*args, **kwargs))
        return header.removeprefix(f"{pydantic_v2_templates.future_annotations}\n\n")


register_generator(MODELS_TYPE, AwareDatetimeGenerator)


def render_models(ddl: str) -> str:
    # create_models prints the generated code even with dump=False; keep the output quiet.
    with redirect_stdout(io.StringIO()):
        result = create_models(
            ddl=ddl,
            models_type=MODELS_TYPE,
            # SQL defaults (now(), gen_random_uuid()) would otherwise be pasted in as Python code.
            defaults_off=True,
            singular=True,
            dump=False,
            exit_silent=True,
        )
    return HEADER + str(result["code"])


def main() -> None:
    MODELS_PATH.write_text(render_models(SCHEMA_PATH.read_text()))


if __name__ == "__main__":
    main()
